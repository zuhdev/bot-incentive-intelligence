/**
 * Evidence Centre: deterministic report generation.
 *
 * The same calculation inputs + rules version produce the same report hash
 * (spec §9). Reports carry full provenance: sources, retrieval timestamps,
 * block references, price provenance, methodology, exclusions, unresolved
 * assumptions and data completeness. Reports NEVER imply official BOT approval.
 */
import { prisma } from "@/lib/db";
import { reportHash } from "@/lib/ingestion/events";
import type { SchemeEvaluation } from "@/lib/rules/types";
import env from "@/lib/env";

export interface EvidenceManifestItem {
  kind: string;
  source: string;
  sourceUrl?: string;
  reference: string;
  retrievedAt: string;
}

export interface EvidenceReportPayload {
  disclaimer: string;
  project: { id: string; name: string; website: string | null; category: string; deployStatus: string };
  schemeCode: string;
  schemeName: string;
  rulesVersion: string;
  sourceUrl: string;
  periodStart: string;
  periodEnd: string;
  calculatedAt: string;
  status: string;
  metrics: SchemeEvaluation["metrics"];
  tier: SchemeEvaluation["tier"];
  estimatedRewardUsd: number | null;
  unresolved: string[];
  warnings: string[];
  dataCompleteness: { metricKey: string; status: string }[];
  addresses: { address: string; type: string; label: string | null; verified: boolean }[];
  chain: { chainId: number; name: string; rpc: string; explorer: string };
  latestBlockObserved: number | null;
  priceProvenance: { symbol: string; priceUsd: string; source: string; takenAt: string }[];
  manifest: EvidenceManifestItem[];
}

const DISCLAIMER =
  "This report was generated by BOT Incentive Intelligence, independent software that is NOT an official BOT Chain product. It does not approve, certify or guarantee any ecosystem reward. BOT Chain retains authority over eligibility, Sybil detection, application review and reward distribution. All figures are preliminary calculations based on publicly documented rules and available evidence.";

export async function generateEvidenceReport(
  projectId: string,
  schemeCode: string,
  createdBy?: string,
): Promise<{ id: string; reportHash: string }> {
  const project = await prisma.project.findUniqueOrThrow({ where: { id: projectId }, include: { addresses: true } });
  const evaluation = await buildEvaluation(projectId, schemeCode);

  const latestBlock = await prisma.block.findFirst({ orderBy: { id: "desc" }, select: { id: true } });
  const prices = await prisma.tokenPrice.findMany({ orderBy: { takenAt: "desc" }, take: 10 });

  const payload: EvidenceReportPayload = {
    disclaimer: DISCLAIMER,
    project: {
      id: project.id,
      name: project.name,
      website: project.website,
      category: project.category,
      deployStatus: project.deployStatus,
    },
    schemeCode: evaluation.schemeCode,
    schemeName: evaluation.schemeName,
    rulesVersion: evaluation.rulesVersion,
    sourceUrl: evaluation.sourceUrl,
    periodStart: evaluation.periodStart,
    periodEnd: evaluation.periodEnd,
    calculatedAt: evaluation.calculatedAt,
    status: evaluation.status,
    metrics: evaluation.metrics,
    tier: evaluation.tier,
    estimatedRewardUsd: evaluation.estimatedRewardUsd,
    unresolved: evaluation.unresolved,
    warnings: evaluation.warnings,
    dataCompleteness: evaluation.metrics.map((m) => ({ metricKey: m.key, status: m.status })),
    addresses: project.addresses.map((a) => ({ address: a.address, type: a.type, label: a.label, verified: a.verified })),
    chain: {
      chainId: env.BOT_CHAIN_ID,
      name: env.BOT_NETWORK === "testnet" ? "BOT Chain Testnet" : "BOT Chain",
      rpc: env.BOT_RPC_URL,
      explorer: env.BOT_EXPLORER_URL,
    },
    latestBlockObserved: latestBlock ? Number(latestBlock.id) : null,
    priceProvenance: prices.map((p) => ({
      symbol: p.symbol,
      priceUsd: p.priceUsd.toString(),
      source: p.source,
      takenAt: p.takenAt.toISOString(),
    })),
    manifest: evaluation.metrics.flatMap((m) =>
      m.sources.map((s) => ({
        kind: "api_response",
        source: s.name,
        sourceUrl: s.url,
        reference: `${m.key}`,
        retrievedAt: s.retrievedAt,
      })),
    ),
  };

  const hash = reportHash(payload);
  const periodStart = new Date(`${evaluation.periodStart}T00:00:00Z`);
  const periodEnd = new Date(`${evaluation.periodEnd}T23:59:59Z`);

  const report = await prisma.evidenceReport.upsert({
    where: {
      projectId_schemeCode_rulesVersion_periodStart_periodEnd_format: {
        projectId,
        schemeCode,
        rulesVersion: evaluation.rulesVersion,
        periodStart,
        periodEnd,
        format: "json",
      },
    },
    create: {
      projectId,
      schemeCode,
      rulesVersion: evaluation.rulesVersion,
      periodStart,
      periodEnd,
      reportHash: hash,
      payload: JSON.stringify(payload, null, 2),
      format: "json",
      createdBy,
    },
    update: { reportHash: hash, payload: JSON.stringify(payload, null, 2) },
  });

  // Evidence items (bounded)
  await prisma.evidenceItem.deleteMany({ where: { reportId: report.id } });
  for (const item of payload.manifest.slice(0, 100)) {
    await prisma.evidenceItem.create({
      data: {
        reportId: report.id,
        kind: item.kind,
        source: item.source,
        sourceUrl: item.sourceUrl,
        reference: item.reference,
        retrievedAt: new Date(item.retrievedAt),
      },
    });
  }

  return { id: report.id, reportHash: hash };
}

async function buildEvaluation(projectId: string, schemeCode: string): Promise<SchemeEvaluation> {
  const metrics = await prisma.projectMetric.findMany({
    where: { projectId, schemeId: schemeCode },
    orderBy: { evaluatedAt: "desc" },
  });
  const latest = metrics[0];
  if (!latest) throw new Error(`no evaluation found for ${schemeCode}; run evaluation first`);
  const def = (await import("@/lib/rules/definitions")).getDefinition(schemeCode, latest.rulesVersion);

  const periodStart = latest.periodStart ? latest.periodStart.toISOString().slice(0, 10) : "";
  const periodEnd = latest.periodEnd ? latest.periodEnd.toISOString().slice(0, 10) : "";

  const evalMetrics = await prisma.projectMetric.findMany({
    where: { projectId, schemeId: schemeCode, rulesVersion: latest.rulesVersion, periodStart: latest.periodStart, periodEnd: latest.periodEnd },
  });

  const eligibility = await prisma.eligibilityResult.findFirst({
    where: { projectId, schemeCode, rulesVersion: latest.rulesVersion },
    orderBy: { calculatedAt: "desc" },
  });
  const details = eligibility ? (JSON.parse(eligibility.details) as { metrics: SchemeEvaluation["metrics"]; warnings: string[] }) : null;

  return {
    schemeCode,
    schemeName: def.name,
    rulesVersion: def.version,
    sourceUrl: def.sourceUrl,
    status: (eligibility?.status as SchemeEvaluation["status"]) ?? "insufficient_data",
    overallProgressPct: eligibility?.scorePct ? eligibility.scorePct.toNumber() : null,
    metrics: details?.metrics ??
      evalMetrics.map((m) => ({
        key: m.metricKey,
        label: m.metricKey,
        value: m.value,
        display: m.value ?? "—",
        status: m.status as never,
        sources: m.attribution ? JSON.parse(m.attribution) : [],
        unresolved: m.unresolved ? JSON.parse(m.unresolved) : [],
        methodology: m.methodology ?? undefined,
      })),
    tier: null,
    estimatedRewardUsd: null,
    unresolved: def.unresolvedInterpretations,
    periodStart,
    periodEnd,
    calculatedAt: (eligibility?.calculatedAt ?? latest.evaluatedAt).toISOString(),
    warnings: details?.warnings ?? [],
  };
}

export function reportToCsv(payload: EvidenceReportPayload): string {
  const rows: string[][] = [
    ["scheme", "metric_key", "metric_label", "status", "value", "target", "progress_pct", "methodology", "unresolved"],
  ];
  for (const m of payload.metrics) {
    rows.push([
      payload.schemeCode,
      m.key,
      m.label,
      m.status,
      m.value !== null ? String(m.value) : "",
      m.target !== null && m.target !== undefined ? String(m.target) : "",
      m.progressPct !== null && m.progressPct !== undefined ? String(m.progressPct) : "",
      (m.methodology ?? "").replace(/[\r\n",]+/g, " "),
      m.unresolved.join("; ").replace(/[\r\n"]+/g, " "),
    ]);
  }
  return rows.map((r) => r.map((c) => `"${c.replace(/"/g, '""')}"`).join(",")).join("\n");
}
